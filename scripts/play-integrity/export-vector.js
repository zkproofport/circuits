#!/usr/bin/env node
/**
 * Write play-integrity/src/test_vectors.nr: a REAL Google Play Integrity
 * verdict (zkPassport's, play-integrity/test-vectors/zkpassport-real-verdict.json,
 * signed by Google with that app's verification key) and synthetic verdicts
 * signed with the INSECURE test Play key (scripts/statement-signer/anchors.js),
 * each changing one field.
 *
 *   node scripts/play-integrity/export-vector.js
 */
const fs = require('fs');
const path = require('path');
const anchors = require('../statement-signer/anchors');
const A = require('../statement-signer/android');

const CIRCUITS = path.resolve(__dirname, '../..');
const OUT = path.join(CIRCUITS, 'play-integrity/src/test_vectors.nr');
const N = anchors.N_P256;
const arr = b => '[' + Array.from(b).map(v => `0x${v.toString(16).padStart(2, '0')}`).join(', ') + ']';
const lowS = sig => {
  let s = BigInt('0x' + sig.subarray(32).toString('hex'));
  if (s > N / 2n) s = N - s;
  return Buffer.concat([sig.subarray(0, 32), Buffer.from(s.toString(16).padStart(64, '0'), 'hex')]);
};
const pad = b => Buffer.concat([b, Buffer.alloc(1368 - b.length)]);

let out = `// GENERATED by scripts/play-integrity/export-vector.js -- do not edit.\n\n`;
const tok = (name, t) => {
  out += `pub global ${name}_PAYLOAD: [u8; 1368] = ${arr(t.payload_b64)};\n`;
  out += `pub global ${name}_LEN: u32 = ${t.payload_b64_len};\n`;
  out += `pub global ${name}_SIG: [u8; 64] = ${arr(t.signature)};\n\n`;
};

// REAL: Google's signature over zkPassport's verdict (UNRECOGNIZED_VERSION).
const real = JSON.parse(fs.readFileSync(path.join(CIRCUITS, 'play-integrity/test-vectors/zkpassport-real-verdict.json'), 'utf8'));
const realB64 = Buffer.from(Buffer.from(real.payload).toString('base64url'));
tok('REAL', { payload_b64: pad(realB64), payload_b64_len: realB64.length, signature: lowS(Buffer.from(real.signature_hex, 'hex')) });
out += `pub global REAL_KEY: [u8; 64] = ${arr(Buffer.from(real.key_x_hex + real.key_y_hex, 'hex'))};\n`;
out += `pub global REAL_PACKAGE: [u8; 25] = ${arr(Buffer.from('app.zkpassport.zkpassport'))};\n\n`;

// SYNTHETIC: the test key, nonce = 32 bytes of 0x07.
const key = anchors.testPlayKey();
const nonce = Buffer.alloc(32, 7);
out += `pub global TEST_KEY: [u8; 64] = ${arr(Buffer.concat([key.x, key.y]))};\n`;
out += `pub global NONCE: [u8; 32] = ${arr(nonce)};\n\n`;
tok('OK_DEVICE', A.playToken(nonce, key));
tok('OK_STRONG_ONLY', A.playToken(nonce, key, { verdicts: ['MEETS_STRONG_INTEGRITY'] }));
tok('OK_ALL_THREE', A.playToken(nonce, key, { verdicts: ['MEETS_BASIC_INTEGRITY', 'MEETS_DEVICE_INTEGRITY', 'MEETS_STRONG_INTEGRITY'] }));
// '=' escaped as Google echoes it: JSON.stringify writes '=' raw, so splice the escape in.
{
  const t = A.playToken(nonce, key, { nonceText: 'NONCEPLACEHOLDER' });
  const json = t.json.replace('NONCEPLACEHOLDER', nonce.toString('base64url') + '\\u003d');
  tok('OK_PADDED_NONCE', A.playToken(nonce, key, { raw: json }));
}
tok('BASIC_ONLY', A.playToken(nonce, key, { verdicts: ['MEETS_BASIC_INTEGRITY'] }));
tok('NO_VERDICT', A.playToken(nonce, key, { verdicts: [] }));
tok('UNRECOGNIZED', A.playToken(nonce, key, { recognition: 'UNRECOGNIZED_VERSION' }));
tok('OTHER_REQUEST_PACKAGE', A.playToken(nonce, key, { requestPackage: 'com.masselabs.zkproofport.debug' }));
tok('OTHER_APP_PACKAGE', A.playToken(nonce, key, { package: 'com.example.other' }));
tok('OTHER_NONCE', A.playToken(Buffer.alloc(32, 8), key));
tok('NONCE_PADDED_RAW', A.playToken(nonce, key, { nonceText: nonce.toString('base64url') + '=' }));
fs.writeFileSync(OUT, out);
console.log('wrote', path.relative(CIRCUITS, OUT));
