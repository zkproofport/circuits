#!/usr/bin/env node
/**
 * Write deps/eth-mpt/src/storage_test_fixture.nr: two real EAS records from
 * Base mainnet, proven at one block, for the storage-slot unit tests.
 *
 *   node scripts/coinbase-eas-storage-poc/make-mpt-test-fixture.js
 *
 * Needs circuits/.env.production (BASE_RPC_URL).
 *
 * LIVE is an unrevoked Coinbase KYC attestation; REVOKED is one Coinbase
 * revoked. Their third struct word -- time | expirationTime | revocationTime --
 * is what the tests read, so the pair shows the revocation is actually seen:
 * the revoked record must be refused when claimed as time alone, and accepted
 * only with its revocation time included.
 */
const { ethers } = require('../node_modules/ethers');
const fs = require('fs');
const path = require('path');

const CIRCUITS_ROOT = path.resolve(__dirname, '../..');
const OUT = path.join(CIRCUITS_ROOT, 'deps/eth-mpt/src/storage_test_fixture.nr');
const EAS = '0x4200000000000000000000000000000000000021';
const RECORDS = {
  LIVE: '0x626de11971b847cef5a29833e122eb98dee0fac462fee1ac54f1b189c8540f59',
  REVOKED: '0xba0756f325cc62d9adf57625f379e2f4e78712552457408882652341dd91597f',
};
const MAX_NODE_LEN = 532;
const MAX_DEPTH_NO_LEAF = 10;
const MAX_LEAF_LEN = 70;

function loadEnv() {
  const file = path.join(CIRCUITS_ROOT, '.env.production');
  if (!fs.existsSync(file)) throw new Error(`${file} is required (BASE_RPC_URL)`);
  const env = Object.fromEntries(
    fs.readFileSync(file, 'utf8').split('\n')
      .filter(l => l.trim() && !l.startsWith('#') && l.includes('='))
      .map(l => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
  );
  if (!env.BASE_RPC_URL) throw new Error(`BASE_RPC_URL missing from ${file}`);
  return env;
}

const arr = bytes => '[' + Array.from(bytes).map(b => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + ']';
const pad = (bytes, len) => {
  if (bytes.length > len) throw new Error(`${bytes.length} bytes exceeds ${len}`);
  const out = new Uint8Array(len);
  out.set(bytes);
  return out;
};

async function main() {
  const provider = new ethers.JsonRpcProvider(loadEnv().BASE_RPC_URL);
  // One eth_getProof for both slots: one block, one root. The RPC sits behind
  // a balancer whose nodes lag each other, so a block a few back is asked for.
  const blockNumber = (await provider.getBlockNumber()) - 5;
  const slots = Object.values(RECORDS).map(uid =>
    ethers.toBeHex(BigInt(ethers.solidityPackedKeccak256(['bytes32', 'uint256'], [uid, 50n])) + 2n, 32));
  const p = await provider.send('eth_getProof', [EAS, slots, ethers.toQuantity(blockNumber)]);
  const root = p.storageHash;
  const lines = [
    '// Generated by circuits/scripts/coinbase-eas-storage-poc/make-mpt-test-fixture.js',
    `// Base block ${blockNumber}. Real EAS records; see the script for what each is.`,
    '',
  ];
  for (const [k, [name, uid]] of Object.entries(RECORDS).entries()) {
    const slot = slots[k];
    const sp = p.storageProof[k];
    if (BigInt(sp.key) !== BigInt(slot)) throw new Error(`proof ${k} is for ${sp.key}, not ${slot}`);
    const word = ethers.getBytes(ethers.zeroPadValue(ethers.toBeHex(BigInt(sp.value)), 32));
    const nodes = sp.proof.map(n => ethers.getBytes(n));
    const internal = nodes.slice(0, -1);
    const nodeRows = [];
    for (let i = 0; i < MAX_DEPTH_NO_LEAF; i++) {
      nodeRows.push('    ' + arr(i < internal.length ? pad(internal[i], MAX_NODE_LEN) : new Uint8Array(MAX_NODE_LEN)));
    }
    const w = BigInt(sp.value);
    console.log(`${name}: ${uid} time ${w & 0xffffffffffffffffn} revocationTime ${(w >> 128n) & 0xffffffffffffffffn}, ${nodes.length} nodes`);
    lines.push(
      `// ${uid}: time ${w & 0xffffffffffffffffn}, revocationTime ${(w >> 128n) & 0xffffffffffffffffn}`,
      `pub(crate) global ${name}_SLOT: [u8; 32] = ${arr(ethers.getBytes(slot))};`,
      `pub(crate) global ${name}_WORD: [u8; 32] = ${arr(word)};`,
      `pub(crate) global ${name}_DEPTH: u64 = ${nodes.length};`,
      `pub(crate) global ${name}_LEAF: [u8; ${MAX_LEAF_LEN}] = ${arr(pad(nodes[nodes.length - 1], MAX_LEAF_LEN))};`,
      `pub(crate) global ${name}_NODES: [[u8; ${MAX_NODE_LEN}]; ${MAX_DEPTH_NO_LEAF}] = [`,
      nodeRows.join(',\n'),
      '];',
      '',
    );
  }
  lines.push(`pub(crate) global STORAGE_ROOT: [u8; 32] = ${arr(ethers.getBytes(root))};`, '');
  fs.writeFileSync(OUT, lines.join('\n'));
  console.log('wrote', path.relative(CIRCUITS_ROOT, OUT));
}

main().catch(e => {
  console.error(e.message || e);
  process.exit(1);
});
