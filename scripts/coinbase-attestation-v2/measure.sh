#!/bin/bash
# Measure coinbase_attestation_v2 against coinbase_attestation v1, with the
# pinned toolchain.
#
#   scripts/coinbase-attestation-v2/measure.sh [runs]     (default 3 runs)
#
# Needs, first:
#   scripts/build.sh coinbase-attestation-v2   (vk; the acceptance run leaves the
#                                               witnesses this proves)
#   coinbase-attestation/Prover.toml           (proofport-ai/scripts/gen-prover-toml.ts)
#
# Prints `bb gates` for v1, v2, and each probe (_probes/coinbase-attestation-v2/
# and the prototype's _probes/coinbase-app-attest-poc/ per-part probes), then
# `bb prove -t evm` wall time and peak RSS (macOS /usr/bin/time -l) per run for:
#   v1                       its own fixture
#   v2, server kind          the REAL circuit (needs the test server key pinned)
#   v2, app kind             the synthetic-anchors copy (same circuit, only the
#                            two anchor constants differ; no real-root app
#                            witness can exist without a device)
# plus the dyadic size (read from the .srs; bb 4.2 does not print it), proof
# and vk sizes. Proof outputs go to a temporary directory and are removed.
set -eu

RUNS=${1:-3}
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CIRCUITS="$(cd "$SCRIPT_DIR/../.." && pwd)"
V2="$CIRCUITS/coinbase-attestation-v2"
SYN="$CIRCUITS/coinbase-attestation-v2-synthetic-anchors"
BASE="$CIRCUITS/coinbase-attestation"
PROBES="$CIRCUITS/_probes/coinbase-attestation-v2"
POC_PROBES="$CIRCUITS/_probes/coinbase-app-attest-poc"

# shellcheck disable=SC1091
. "$CIRCUITS/toolchain.env"
[ "$(bb --version)" = "$BB_VERSION" ] || { echo "bb is $(bb --version), toolchain.env pins $BB_VERSION" >&2; exit 1; }
[ "$(nargo --version | sed -n 's/^nargo version = //p')" = "$NARGO_VERSION" ] || { echo "nargo is not $NARGO_VERSION" >&2; exit 1; }

gates() { bb gates -b "$1" 2>/dev/null | sed -n 's/.*"circuit_size": *\([0-9]*\).*/\1/p' | head -1; }
opcodes() { bb gates -b "$1" 2>/dev/null | sed -n 's/.*"acir_opcodes": *\([0-9]*\).*/\1/p' | head -1; }

# The base probe is derived from the circuit, so it cannot drift from it:
# main.nr with every statement input and PART 3 removed.
mkdir -p "$PROBES/coinbase-base/src"
python3 -I - "$V2/src/main.nr" "$PROBES/coinbase-base/src/main.nr" <<'PY'
import re, sys
src = open(sys.argv[1]).read()
body = src[src.index('mod client_data;'):]
for line in ['mod client_data;\n', 'mod apple_ca;\n', 'mod server_key;\n',
             'use client_data::{CLIENT_DATA_LEN, check_client_data};\n',
             'use apple_ca::APPLE_APP_ATTESTATION_CA_KEY;\n', 'use server_key::SERVER_KEY;\n']:
    if line not in body:
        sys.exit(f'{line.strip()} not in main.nr: the probe generator is stale')
    body = body.replace(line, '')
body, n1 = re.subn(r'use app_attest::\{[^}]*\};\n', '', body)
def cut(b, s, e):
    if s not in b or e not in b[b.index(s):]:
        sys.exit(f'cannot find {s!r} .. {e!r} in main.nr: the probe generator is stale')
    return b[:b.index(s)] + b[b.index(e, b.index(s)):]
body = cut(body, '/// The private signer-kind byte.', '/// attestAccount(address)')
body = cut(body, '    // ============ Public Input (the statement\'s time) ============', '    // ============ Private Inputs ============')
body = cut(body, '    // The statement, and who signed it.', ') {\n')
body = cut(body, '    // ===================================================================\n    // PART 3', '    // ===================================================================\n    // PART 4')
for g in ['APP_ID', 'APP_ID_HASH']:
    m = re.search(r'(///[^\n]*\n)*global ' + g + r': \[u8; \d+\] = \[[^\]]*\];[^\n]*\n\n', body)
    if not m:
        sys.exit(f'could not find global {g} in main.nr: the probe generator is stale')
    body = body.replace(m.group(0), '')
if n1 != 1 or any(w in body for w in ['app_attest', 'client_data', 'SERVER_KEY', 'signer_kind', 'attested_at']):
    sys.exit('statement code survived in the base probe: the generator is stale')
hdr = ('// GENERATED by scripts/coinbase-attestation-v2/measure.sh from coinbase-attestation-v2/src/main.nr:\n'
       '// the circuit with the statement (PART 3) and its inputs removed. Do not edit.\n\n')
open(sys.argv[2], 'w').write(hdr + body)
PY
cat > "$PROBES/coinbase-base/Nargo.toml" <<'TOML'
[package]
name = "probe_coinbase_base"
type = "bin"
authors = ["zkproofport"]

[dependencies]
keccak256 = { path = "../../../deps/keccak256" }
coinbase_libs = { path = "../../../coinbase-libs" }
TOML

# What the `if signer_kind == KIND_APP` branch costs: the same circuit with the
# App Attest checks run unconditionally (it would refuse every server-kind
# witness, so it is a measurement, never a circuit).
mkdir -p "$PROBES/unconditional-app-checks/src"
cp "$V2/src/"*.nr "$PROBES/unconditional-app-checks/src/"
python3 -I - "$PROBES/unconditional-app-checks/src/main.nr" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read()
want = '    if signer_kind == KIND_APP {\n'
if s.count(want) != 1:
    sys.exit('the app branch is not where measure.sh expects it: the probe generator is stale')
s = s.replace(want, '    {\n')
open(p, 'w').write('// GENERATED by scripts/coinbase-attestation-v2/measure.sh: v2 with the app branch\n'
                   '// unconditional. A measurement only. Do not edit.\n\n' + s)
PY
sed 's/^name = .*/name = "probe_unconditional_app_checks"/; s#path = "\.\./#path = "../../../#' "$V2/Nargo.toml" > "$PROBES/unconditional-app-checks/Nargo.toml"

echo ""
echo "bb gates ($BB_VERSION, nargo $NARGO_VERSION)"
printf '  %-44s %12s %12s\n' "circuit" "circuit_size" "acir_opcodes"
row() { printf '  %-44s %12s %12s\n' "$1" "$(gates "$2")" "$(opcodes "$2")"; }
row "coinbase_attestation v1 (main)" "$BASE/target/coinbase_attestation.json"
row "coinbase_attestation_v2" "$V2/target/coinbase_attestation_v2.json"
for p in coinbase-base unconditional-app-checks root-link sha384-intermediate; do
  (cd "$PROBES/$p" && nargo compile > /dev/null 2>&1) || { echo "probe $p does not compile" >&2; exit 1; }
  row "  probe $p" "$PROBES/$p/target/probe_$(echo "$p" | tr - _).json"
done
for p in p384-verify cert-der-sha p256-assertion; do
  (cd "$POC_PROBES/$p" && nargo compile > /dev/null 2>&1) || { echo "probe $p does not compile" >&2; exit 1; }
  row "  prototype probe $p" "$POC_PROBES/$p/target/probe_$(echo "$p" | tr - _).json"
done

[ -f "$BASE/Prover.toml" ] || { echo "$BASE/Prover.toml missing: run proofport-ai/scripts/gen-prover-toml.ts" >&2; exit 1; }
(cd "$BASE" && nargo execute witness_measure > /dev/null 2>&1) || { echo "coinbase_attestation witness failed" >&2; exit 1; }
[ -f "$SYN/target/witness_action.gz" ] || { echo "run scripts/build.sh coinbase-attestation-v2 first (no app-kind witness)" >&2; exit 1; }
[ -f "$V2/target/witness_real_server_action.gz" ] || { echo "run scripts/build.sh coinbase-attestation-v2 first (no server-kind witness on the real circuit)" >&2; exit 1; }

OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' EXIT

prove() {
  local label="$1" json="$2" witness="$3" vk="$4"
  echo ""
  echo "bb prove -t evm: $label ($RUNS runs)"
  for i in $(seq 1 "$RUNS"); do
    mkdir -p "$OUT/$label"
    /usr/bin/time -l bb prove -b "$json" -w "$witness" -k "$vk" -o "$OUT/$label" -t evm > "$OUT/$label.log" 2>&1 \
      || { echo "  prove failed:"; tail -5 "$OUT/$label.log"; exit 1; }
    local real rss
    real=$(awk '/ real /{print $1}' "$OUT/$label.log" | tail -1)
    rss=$(awk '/maximum resident set size/{printf "%.2f", $1/1024/1024/1024}' "$OUT/$label.log")
    printf '  run %d: %6s s  peak RSS %s GiB\n' "$i" "$real" "$rss"
  done
  bb verify -p "$OUT/$label/proof" -i "$OUT/$label/public_inputs" -k "$vk" -t evm > /dev/null 2>&1 \
    && echo "  verified" || { echo "  bb verify FAILED"; exit 1; }
  echo "  proof $(wc -c < "$OUT/$label/proof" | tr -d ' ') bytes, public inputs $(wc -c < "$OUT/$label/public_inputs" | tr -d ' ') bytes, vk $(wc -c < "$vk" | tr -d ' ') bytes"
  # The .srs scripts/build.sh writes holds dyadic size + 1 points of 64 bytes
  # (noir-rs srs_downloader), so it says.
  local srs="${json%.json}.srs"
  if [ -f "$srs" ]; then
    echo "  dyadic size 2^$(awk -v b="$(wc -c < "$srs")" 'BEGIN { n = int(b / 64); l = 0; while (2 ^ (l + 1) <= n) l++; print l }') (from $(basename "$srs"), $(wc -c < "$srs" | tr -d ' ') bytes)"
  else
    echo "  dyadic size: no .srs beside the circuit to read it from"
  fi
}

prove coinbase_attestation_v1 "$BASE/target/coinbase_attestation.json" "$BASE/target/witness_measure.gz" "$BASE/target/vk/vk"
prove v2_server_kind_real "$V2/target/coinbase_attestation_v2.json" "$V2/target/witness_real_server_action.gz" "$V2/target/vk/vk"
prove v2_app_kind_synthetic "$SYN/target/coinbase_attestation_v2.json" "$SYN/target/witness_action.gz" "$SYN/target/vk/vk"
echo ""
