#!/usr/bin/env node
/**
 * Fixtures for _probes/coinbase-app-attest-poc/trust-anchor-branch: the merged
 * app / server branch under one trust-anchor root. ALL KEYS ARE SYNTHETIC:
 * a P-384 key of ours plays Apple's App Attestation CA, P-256 keys play the
 * Secure Enclave key and the AI server keys.
 *
 *   node generate-trust-anchor-fixtures.js --probes <_probes/coinbase-app-attest-poc>
 *
 * The trust-anchor set is a depth-2 Poseidon2 tree:
 *   index 0  app     SHA256(CA X || Y)
 *   index 1  server  SHA256(server X || Y || 32 zero bytes)
 *   index 2  server  SHA256(second server key, same shape)   -- a rotation slot
 *   index 3  empty   (Field 0)
 * The tree is computed by the anchor-root helper circuit through
 * `nargo execute`, so this script and the circuit cannot disagree on Poseidon2.
 *
 * Writes, in trust-anchor-branch/ (all gitignored as Prover.*.toml):
 *   Prover.accept_app.toml, Prover.accept_server.toml
 *   Prover.refuse_<case>.toml -- each with the refusal it must produce,
 *   listed in cases.json for the acceptance script.
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { APP_ID, N_P256, N_P384, TBS_MAX, sha256, credentialTbs, ecKey, signLowS, arr, pad } = require('./generate-prover-toml.js');

const args = process.argv.slice(2);
const i = args.indexOf('--probes');
if (i === -1 || !args[i + 1]) throw new Error('--probes is required');
const PROBES = path.resolve(args[i + 1]);
const ROOT_DIR = path.join(PROBES, 'anchor-root');
const OUT_DIR = path.join(PROBES, 'trust-anchor-branch');

const KIND_APP = 1;
const KIND_SERVER = 2;

const fieldHex = v => '0x' + BigInt(v).toString(16).padStart(64, '0');

function poseidonTree(slots) {
  const toml = [
    `kinds = [${slots.map(s => s.kind ?? 0).join(', ')}]`,
    `key_hashes = [${slots.map(s => arr(s.keyHash ?? Buffer.alloc(32))).join(', ')}]`,
    `used = [${slots.map(s => (s.keyHash ? 'true' : 'false')).join(', ')}]`,
  ].join('\n');
  fs.writeFileSync(path.join(ROOT_DIR, 'Prover.toml'), toml + '\n');
  const out = execFileSync('nargo', ['execute'], { cwd: ROOT_DIR, encoding: 'utf8' });
  const m = out.match(/Circuit output: \[([^\]]*)\]/);
  if (!m) throw new Error(`anchor-root printed no output array:\n${out}`);
  const v = m[1].split(',').map(x => BigInt(x.trim()));
  if (v.length !== 7) throw new Error(`anchor-root returned ${v.length} values, expected 7`);
  return { leaves: v.slice(0, 4), n0: v[4], n1: v[5], root: v[6] };
}

function main() {
  const ca = ecKey('secp384r1');
  const fakeCa = ecKey('secp384r1');
  const cred = ecKey('prime256v1');
  const otherCred = ecKey('prime256v1');
  const server = ecKey('prime256v1');
  const server2 = ecKey('prime256v1');
  const outsider = ecKey('prime256v1');
  const attacker = ecKey('prime256v1');

  const caKey = Buffer.concat([ca.x, ca.y]);
  const fakeCaKey = Buffer.concat([fakeCa.x, fakeCa.y]);
  const serverKey = k => Buffer.concat([k.x, k.y, Buffer.alloc(32)]);

  const tbsFor = key => credentialTbs({
    x: key.x, y: key.y, keyId: sha256(Buffer.from([4]), key.x, key.y),
    nonce: sha256(crypto.randomBytes(32)), appId: APP_ID,
    serial: Buffer.concat([Buffer.from([0x01]), crypto.randomBytes(5)]),
  });
  const tbs = tbsFor(cred);
  const certSig = signLowS('sha256', tbs, ca, N_P384, 48);
  const otherTbs = tbsFor(otherCred);
  // The server kind still has to hand the parser a well-formed TBS; any one
  // will do. This one is for a throwaway key and is never signed by a CA.
  const placeholder = ecKey('prime256v1');
  const placeholderTbs = tbsFor(placeholder);
  const placeholderSig = signLowS('sha256', placeholderTbs, fakeCa, N_P384, 48);
  // An attacker's own "certificate" for their own key, signed by their own
  // P-384 key, presented under the real CA anchor.
  const attackerTbs = tbsFor(attacker);
  const attackerCertSig = signLowS('sha256', attackerTbs, fakeCa, N_P384, 48);
  for (const t of [tbs, otherTbs, placeholderTbs, attackerTbs]) if (t.length > TBS_MAX) throw new Error(`TBS is ${t.length} bytes`);

  const statement = sha256(Buffer.from('ZKProofport trust-anchor probe statement'));
  // signLowS hashes its message with SHA-256, so the circuit's digest is
  // SHA256(statement) -- the 32-byte value made public below.
  const digest = sha256(statement);
  const sign = key => signLowS('sha256', statement, key, N_P256, 32);

  const tree = poseidonTree([
    { kind: KIND_APP, keyHash: sha256(caKey) },
    { kind: KIND_SERVER, keyHash: sha256(serverKey(server)) },
    { kind: KIND_SERVER, keyHash: sha256(serverKey(server2)) },
    {},
  ]);
  const pathFor = idx => {
    const sib = tree.leaves[idx ^ 1];
    const up = idx < 2 ? tree.n1 : tree.n0;
    return [sib, up];
  };

  const toml = w => `# SYNTHETIC keys -- generated by scripts/coinbase-app-attest-poc/generate-trust-anchor-fixtures.js
trust_anchor_root = "${fieldHex(w.root ?? tree.root)}"
statement_digest = ${arr(digest)}
kind = ${w.kind}
anchor_key = ${arr(w.anchorKey)}
anchor_index = ${w.index}
anchor_path = [${w.path.map(v => `"${fieldHex(v)}"`).join(', ')}]
credential_tbs = ${arr(pad(w.tbs, TBS_MAX, 'TBS'))}
credential_tbs_len = ${w.tbs.length}
credential_sig = ${arr(w.certSig)}
statement_sig = ${arr(w.stmtSig)}
`;

  const app = { kind: KIND_APP, anchorKey: caKey, index: 0, path: pathFor(0), tbs, certSig, stmtSig: sign(cred) };
  const srv = { kind: KIND_SERVER, anchorKey: serverKey(server), index: 1, path: pathFor(1), tbs: placeholderTbs, certSig: placeholderSig, stmtSig: sign(server) };
  const srv2 = { ...srv, anchorKey: serverKey(server2), index: 2, path: pathFor(2), stmtSig: sign(server2) };

  const MEMBER = 'Trust anchor is not in the published set';
  const CERT = 'Credential certificate is not signed by the trust anchor';
  const STMT = 'Statement signature is invalid';
  const cases = {
    accept_app: [app, null],
    accept_server: [srv, null],
    accept_server_rotated: [srv2, null],
    // 1. server kind with a key that is not in the root.
    refuse_server_key_not_in_root: [{ ...srv, anchorKey: serverKey(outsider), stmtSig: sign(outsider) }, MEMBER],
    // 2. app kind with a bad certificate.
    // The real certificate signature, moved onto a TBS for a key the
    // prover holds, and the statement signed by that key.
    refuse_app_cert_tampered: [{ ...app, tbs: otherTbs, stmtSig: sign(otherCred) }, CERT],
    refuse_app_cert_self_made: [{ ...app, tbs: attackerTbs, certSig: attackerCertSig, stmtSig: sign(attacker) }, CERT],
    refuse_app_ca_not_in_root: [{ ...app, anchorKey: fakeCaKey, certSig: signLowS('sha256', tbs, fakeCa, N_P384, 48) }, MEMBER],
    // 3. kind flipped.
    refuse_kind_flipped_app_to_server: [{ ...app, kind: KIND_SERVER }, MEMBER],
    refuse_kind_flipped_server_to_app: [{ ...srv, kind: KIND_APP }, MEMBER],
    // The flip that does land on an app leaf: real CA anchor, but only the
    // placeholder certificate, and the statement signed by the placeholder key.
    refuse_kind_app_with_placeholder_cert: [{ ...srv, kind: KIND_APP, anchorKey: caKey, index: 0, path: pathFor(0), stmtSig: sign(placeholder) }, CERT],
    // 4. statement signed by another key.
    refuse_app_statement_other_key: [{ ...app, stmtSig: sign(otherCred) }, STMT],
    refuse_server_statement_other_key: [{ ...srv, stmtSig: sign(outsider) }, STMT],
    // Also.
    refuse_kind_unknown: [{ ...srv, kind: 3 }, 'Unknown trust anchor kind'],
    refuse_index_outside_tree: [{ ...srv, index: 5 }, 'Trust anchor index is outside the tree'],
    refuse_server_key_padding: [{ ...srv, anchorKey: Buffer.concat([server.x, server.y, Buffer.alloc(31), Buffer.from([1])]) }, MEMBER],
  };

  const list = [];
  for (const [name, [w, expect]] of Object.entries(cases)) {
    fs.writeFileSync(path.join(OUT_DIR, `Prover.${name}.toml`), toml(w));
    list.push({ name, expect });
  }
  fs.writeFileSync(path.join(OUT_DIR, 'target', 'cases.json'), JSON.stringify(list, null, 2) + '\n');
  console.log(`trust_anchor_root ${fieldHex(tree.root)}; ${list.length} fixtures in ${path.relative(process.cwd(), OUT_DIR)}`);
}

try {
  main();
} catch (e) {
  console.error(e.message || e);
  process.exit(1);
}
