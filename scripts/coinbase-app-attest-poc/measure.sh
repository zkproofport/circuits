#!/bin/bash
# Measure coinbase_app_attest_poc against coinbase_attestation, with the
# pinned toolchain.
#
#   scripts/coinbase-app-attest-poc/measure.sh [runs]     (default 3 runs)
#
# Needs, first:
#   scripts/build.sh coinbase-app-attest-poc   (vk, and the acceptance run's
#                                               target/witness_action.gz)
#   coinbase-attestation/Prover.toml           (proofport-ai/scripts/gen-prover-toml.ts)
#
# Prints: `bb gates` for the whole circuit and for each probe under
# _probes/coinbase-app-attest-poc/, then `bb prove -t evm` wall time and peak
# RSS (macOS /usr/bin/time -l) per run, the dyadic size (read from the .srs,
# since bb 4.2 does not print it), proof and vk sizes. Proof outputs go to a temporary directory and are removed.
set -eu

RUNS=${1:-3}
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CIRCUITS="$(cd "$SCRIPT_DIR/../.." && pwd)"
POC="$CIRCUITS/coinbase-app-attest-poc"
BASE="$CIRCUITS/coinbase-attestation"
PROBES="$CIRCUITS/_probes/coinbase-app-attest-poc"

# shellcheck disable=SC1091
. "$CIRCUITS/toolchain.env"
[ "$(bb --version)" = "$BB_VERSION" ] || { echo "bb is $(bb --version), toolchain.env pins $BB_VERSION" >&2; exit 1; }
[ "$(nargo --version | sed -n 's/^nargo version = //p')" = "$NARGO_VERSION" ] || { echo "nargo is not $NARGO_VERSION" >&2; exit 1; }

gates() { bb gates -b "$1" 2>/dev/null | sed -n 's/.*"circuit_size": *\([0-9]*\).*/\1/p' | head -1; }
opcodes() { bb gates -b "$1" 2>/dev/null | sed -n 's/.*"acir_opcodes": *\([0-9]*\).*/\1/p' | head -1; }

# The base probe is derived from the circuit, so it cannot drift from it.
python3 -I - "$POC/src/main.nr" "$PROBES/coinbase-base/src/main.nr" <<'PY'
import re, sys
src = open(sys.argv[1]).read()
body = src[src.index('mod client_data;'):]
body = body.replace('mod client_data;\n', '')
body, n1 = re.subn(r'use app_attest::\{[^}]*\};\n', '', body)
body = body.replace('use client_data::{CLIENT_DATA_LEN, check_client_data};\n', '')
cut = lambda b, s, e: b[:b.index(s)] + b[b.index(e, b.index(s)):]
body = cut(body, '    // ============ Public Inputs (App Attest) ============', '    // ============ Private Inputs ============')
body = cut(body, '    client_data: [u8; CLIENT_DATA_LEN],', ') {\n')
body = cut(body, '    // ===================================================================\n    // PART 3', '    // ===================================================================\n    // PART 4')
for g in ['APP_ID', 'APP_ID_HASH']:
    m = re.search(r'(///[^\n]*\n)*global ' + g + r': \[u8; \d+\] = \[[^\]]*\];[^\n]*\n\n', body)
    if not m:
        sys.exit(f'could not find global {g} in main.nr: the probe generator is stale')
    body = body.replace(m.group(0), '')
if n1 != 1 or 'app_attest' in body or 'client_data' in body:
    sys.exit('App Attest code survived in the base probe: the generator is stale')
hdr = ('// GENERATED by scripts/coinbase-app-attest-poc/measure.sh from coinbase-app-attest-poc/src/main.nr:\n'
       '// the circuit with its App Attest inputs and PART 3 removed. Do not edit.\n\n')
open(sys.argv[2], 'w').write(hdr + body)
PY

echo ""
echo "bb gates ($BB_VERSION, nargo $NARGO_VERSION)"
printf '  %-34s %12s %12s\n' "circuit" "circuit_size" "acir_opcodes"
row() { printf '  %-34s %12s %12s\n' "$1" "$(gates "$2")" "$(opcodes "$2")"; }
row "coinbase_attestation (main)" "$BASE/target/coinbase_attestation.json"
row "coinbase_app_attest_poc" "$POC/target/coinbase_app_attest_poc.json"
for p in coinbase-base p384-verify cert-der-sha p256-assertion; do
  (cd "$PROBES/$p" && nargo compile > /dev/null 2>&1) || { echo "probe $p does not compile" >&2; exit 1; }
  name=probe_$(echo "$p" | tr - _)
  row "  probe $p" "$PROBES/$p/target/$name.json"
done

# A witness for the baseline, from its own fixture.
[ -f "$BASE/Prover.toml" ] || { echo "$BASE/Prover.toml missing: run proofport-ai/scripts/gen-prover-toml.ts" >&2; exit 1; }
(cd "$BASE" && nargo execute witness_measure > /dev/null 2>&1) || { echo "coinbase_attestation witness failed" >&2; exit 1; }
[ -f "$POC/target/witness_action.gz" ] || { echo "run scripts/build.sh coinbase-app-attest-poc first (no witness_action.gz)" >&2; exit 1; }

OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' EXIT

prove() {
  local label="$1" json="$2" witness="$3" vk="$4"
  echo ""
  echo "bb prove -t evm: $label ($RUNS runs)"
  for i in $(seq 1 "$RUNS"); do
    mkdir -p "$OUT/$label"
    /usr/bin/time -l bb prove -b "$json" -w "$witness" -k "$vk" -o "$OUT/$label" -t evm > "$OUT/$label.log" 2>&1 \
      || { echo "  prove failed:"; tail -5 "$OUT/$label.log"; exit 1; }
    local real rss
    real=$(awk '/ real /{print $1}' "$OUT/$label.log" | tail -1)
    rss=$(awk '/maximum resident set size/{printf "%.2f", $1/1024/1024/1024}' "$OUT/$label.log")
    printf '  run %d: %6s s  peak RSS %s GiB\n' "$i" "$real" "$rss"
  done
  bb verify -p "$OUT/$label/proof" -i "$OUT/$label/public_inputs" -k "$vk" -t evm > /dev/null 2>&1 \
    && echo "  verified" || { echo "  bb verify FAILED"; exit 1; }
  echo "  proof $(wc -c < "$OUT/$label/proof" | tr -d ' ') bytes, public inputs $(wc -c < "$OUT/$label/public_inputs" | tr -d ' ') bytes, vk $(wc -c < "$vk" | tr -d ' ') bytes"
  # bb 4.2 prints no dyadic size. The .srs that scripts/build.sh writes holds
  # dyadic size + 1 points of 64 bytes (noir-rs srs_downloader), so it says.
  local srs="${json%.json}.srs"
  if [ -f "$srs" ]; then
    echo "  dyadic size 2^$(awk -v b="$(wc -c < "$srs")" 'BEGIN { n = int(b / 64); l = 0; while (2 ^ (l + 1) <= n) l++; print l }') (from $(basename "$srs"), $(wc -c < "$srs" | tr -d ' ') bytes)"
  else
    echo "  dyadic size: no .srs beside the circuit to read it from"
  fi
}

prove coinbase_attestation "$BASE/target/coinbase_attestation.json" "$BASE/target/witness_measure.gz" "$BASE/target/vk/vk"
prove coinbase_app_attest_poc "$POC/target/coinbase_app_attest_poc.json" "$POC/target/witness_action.gz" "$POC/target/vk/vk"
echo ""
