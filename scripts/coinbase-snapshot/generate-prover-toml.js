#!/usr/bin/env node
/**
 * Build a Prover.toml for coinbase_snapshot_poc from a snapshot file.
 *
 *   ATTESTED_WALLET_KEY=0x... node generate-prover-toml.js [options]
 *
 * Options:
 *   --snapshot <file>   default: the newest coinbase-snapshot-poc/snapshots/<block>.json
 *   --action            sign an EIP-712 action instead of signal_hash
 *   --not-member        sign with a fresh wallet that is in no snapshot, and
 *                       hand it the KYC wallet's path -- what someone outside
 *                       the set (a revoked wallet, after the next root) holds
 *   --out <path>
 *
 * The path is computed here from the whole snapshot, the way the app must do
 * it: asking a server for one index would tell that server who is proving.
 */
const { ethers } = require('../node_modules/ethers');
const fs = require('fs');
const path = require('path');
const { buildLevels, pathOf } = require('./tree');

const CIRCUITS_ROOT = path.resolve(__dirname, '../..');
const SNAP_DIR = path.join(CIRCUITS_ROOT, 'coinbase-snapshot-poc/snapshots');
const CIRCUIT_TAG = ethers.getBytes(ethers.keccak256(ethers.toUtf8Bytes('coinbase_snapshot_poc')));
const ZERO32 = new Uint8Array(32);

const args = process.argv.slice(2);
const opt = name => {
  const i = args.indexOf(name);
  return i === -1 ? null : args[i + 1];
};
const WITH_ACTION = args.includes('--action');
const NOT_MEMBER = args.includes('--not-member');
const OUT = path.resolve(opt('--out') || path.join(CIRCUITS_ROOT, 'coinbase-snapshot-poc/Prover.toml'));

const bytes = b => '[' + Array.from(b).map(x => `0x${x.toString(16).padStart(2, '0')}`).join(', ') + ']';
const fields = f => '[' + f.map(x => `"${ethers.toBeHex(x, 32)}"`).join(', ') + ']';

function newestSnapshot() {
  const files = fs.existsSync(SNAP_DIR) ? fs.readdirSync(SNAP_DIR).filter(f => /^\d+\.json$/.test(f)) : [];
  if (!files.length) throw new Error(`no snapshot in ${SNAP_DIR}; run build-snapshot.js first`);
  files.sort((a, b) => Number(a.split('.')[0]) - Number(b.split('.')[0]));
  return path.join(SNAP_DIR, files[files.length - 1]);
}

function main() {
  if (!process.env.ATTESTED_WALLET_KEY) throw new Error('ATTESTED_WALLET_KEY is required');
  const kyc = new ethers.Wallet(process.env.ATTESTED_WALLET_KEY);
  const signer = NOT_MEMBER ? ethers.Wallet.createRandom() : kyc;
  const file = opt('--snapshot') || newestSnapshot();
  const snap = JSON.parse(fs.readFileSync(file, 'utf8'));

  const t0 = Date.now();
  const tree = buildLevels(snap.addresses.map(a => BigInt(a)), snap.rule.treeDepth);
  const rebuilt = ethers.toBeHex(tree.root, 32);
  if (rebuilt !== snap.root) throw new Error(`snapshot root ${snap.root} does not rebuild (got ${rebuilt})`);
  const index = snap.addresses.indexOf(kyc.address.toLowerCase());
  if (index < 0) throw new Error(`${kyc.address} is not in snapshot ${snap.block.number}`);
  const { siblings, bits } = pathOf(tree, index, snap.rule.treeDepth);
  const treeMs = Date.now() - t0;

  const scope = ethers.getBytes(ethers.keccak256(ethers.toUtf8Bytes('coinbase-snapshot-poc-scope')));
  const userAddress = ethers.getBytes(signer.address);
  const secret = ethers.getBytes(ethers.keccak256(ethers.concat([userAddress, CIRCUIT_TAG])));
  const nullifier = ethers.getBytes(ethers.keccak256(ethers.concat([secret, scope])));

  let signalHash = ethers.getBytes(ethers.keccak256(ethers.toUtf8Bytes('coinbase-snapshot-poc-signal')));
  let domainSeparator = ZERO32;
  let actionHash = ZERO32;
  let digest = ethers.hashMessage(signalHash);
  if (WITH_ACTION) {
    const domain = { name: 'Coinbase Snapshot PoC', version: '1', chainId: 8453, verifyingContract: snap.rule.eas };
    const types = { Join: [{ name: 'member', type: 'address' }, { name: 'nonce', type: 'string' }] };
    const message = { member: signer.address, nonce: 'coinbase-snapshot-poc-1' };
    domainSeparator = ethers.getBytes(ethers.TypedDataEncoder.hashDomain(domain));
    actionHash = ethers.getBytes(ethers.TypedDataEncoder.hashStruct('Join', types, message));
    signalHash = ZERO32;
    digest = ethers.TypedDataEncoder.hash(domain, types, message);
  }
  const sig = signer.signingKey.sign(digest);
  const pub = ethers.getBytes(signer.signingKey.publicKey);

  console.log('snapshot:   ', path.relative(CIRCUITS_ROOT, file), `block ${snap.block.number}, ${snap.count} addresses`);
  console.log('root:       ', snap.root, `(rebuilt in ${treeMs} ms)`);
  console.log('wallet:     ', signer.address, NOT_MEMBER ? '(NOT a member; using the KYC wallet path)' : `(index ${index})`);
  console.log('mode:       ', WITH_ACTION ? 'EIP-712 action' : 'signal hash');

  const toml = `# Generated by scripts/coinbase-snapshot/generate-prover-toml.js
# Snapshot block ${snap.block.number} ${snap.block.hash}, ${snap.count} addresses
# Mode: ${WITH_ACTION ? 'EIP-712 action' : 'signal hash'}${NOT_MEMBER ? ', NOT a member' : ''}

signal_hash = ${bytes(signalHash)}

domain_separator = ${bytes(domainSeparator)}

action_hash = ${bytes(actionHash)}

snapshot_root = "${snap.root}"

scope = ${bytes(scope)}

nullifier = ${bytes(nullifier)}

user_address = ${bytes(userAddress)}

user_signature = ${bytes(ethers.getBytes(ethers.concat([sig.r, sig.s])))}

user_pubkey_x = ${bytes(pub.slice(1, 33))}

user_pubkey_y = ${bytes(pub.slice(33, 65))}

path_siblings = ${fields(siblings)}

path_bits = [${bits.join(', ')}]
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, toml);
  console.log('wrote', path.relative(CIRCUITS_ROOT, OUT));
}

try {
  main();
} catch (e) {
  console.error(e.message || e);
  process.exit(1);
}
