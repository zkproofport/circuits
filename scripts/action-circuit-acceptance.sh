#!/bin/bash
# Acceptance run for a circuit that signs an EIP-712 action OR a signal hash.
#
# `giwa_attestation`, `dojang_playground`, `coinbase_attestation_v2` and `coinbase_country_attestation_v2` (every package of each) work this way. The run takes the circuit directory rather
# than assuming GIWA, so the next circuit with the same branch reuses it instead
# of growing a second copy -- two copies of an acceptance run is how two
# circuits come to be checked to different standards.
#
# WHAT IT PROVES. Both modes are exercised against a REAL attestation
# transaction, so the raw EIP-1559 parsing and the attester key recovery are
# checked against bytes a chain actually holds rather than bytes we invented.
# The refusals matter as much: a circuit that accepts the happy fixture and
# also accepts a tampered one has not been tested, it has been demonstrated.
#
# Each refusal is derived from a committed-nowhere fixture by rewriting ONE
# field, and `tamper-fixture.js` refuses to write a file when the rewrite would
# change nothing -- a "tamper" that tampers with nothing would pass for the
# wrong reason. No network is needed for any of them.
#
# Usage:
#   scripts/action-circuit-acceptance.sh <circuit-dir>
#
# Fixtures (`Prover.toml`, `Prover.no-action.toml`) are gitignored everywhere in
# this repo. Each circuit says how to rebuild its own below.

set -u
# A NODE_OPTIONS that preloads a file which no longer exists (a terminal
# wrapper's temporary preload, 2026-10-28) makes every `node` here crash
# before running; these scripts need none.
unset NODE_OPTIONS

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CIRCUITS_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

CIRCUIT_REL="${1:-}"
if [ -z "$CIRCUIT_REL" ]; then
    echo "Usage: $0 <circuit-dir>   (e.g. giwa-attestation)"
    exit 1
fi

CIRCUIT_DIR="$CIRCUITS_ROOT/$CIRCUIT_REL"
if [ ! -d "$CIRCUIT_DIR" ]; then
    echo "No such circuit directory: $CIRCUIT_DIR"
    exit 1
fi

# The package name, read from the circuit rather than guessed from the folder:
# the two differ (`giwa-attestation` builds `giwa_attestation`).
CIRCUIT_NAME=$(grep -m1 '^name' "$CIRCUIT_DIR/Nargo.toml" | sed 's/.*= *"\(.*\)"/\1/')
TAMPER="$SCRIPT_DIR/giwa-poc/tamper-fixture.js"
VECTORS="$CIRCUIT_DIR/test-vectors"
CIRCUIT_JSON="$CIRCUIT_DIR/target/${CIRCUIT_NAME}.json"

# How this circuit rebuilds its fixtures. They need a key and a network, so
# they are not committed and are regenerated by the script that owns them.
case "$CIRCUIT_REL" in
    giwa-attestation)
        REGEN="$SCRIPT_DIR/giwa-poc/make-fixtures.sh"
        REGEN_NEEDS="$CIRCUITS_ROOT/.env.development"
        ;;
    dojang-playground)
        REGEN="$SCRIPT_DIR/dojang-playground/make-fixtures.sh"
        REGEN_NEEDS="$CIRCUITS_ROOT/.env.development"
        ;;
    coinbase-attestation-v2-synthetic-anchors)
        # coinbase_attestation_v2 with Apple's root and the server key replaced
        # by keys the fixture generator holds (make-fixtures.sh builds this
        # copy from the circuit's source; only those two constants differ).
        # Real Coinbase attestation; the wallet key lives in the parent
        # repository's proofport-ai/.env.test.
        REGEN="$SCRIPT_DIR/coinbase-attestation-v2/make-fixtures.sh"
        REGEN_NEEDS="$CIRCUITS_ROOT/../proofport-ai/.env.test"
        ;;
    coinbase-country-attestation-v2-synthetic-anchors)
        # coinbase_country_attestation v2, anchors replaced as for KYC v2.
        # Real attestCountry transaction; same wallet key.
        REGEN="$SCRIPT_DIR/coinbase-country-attestation-v2/make-fixtures.sh"
        REGEN_NEEDS="$CIRCUITS_ROOT/../proofport-ai/.env.test"
        ;;
    coinbase-country-attestation-v2-android-synthetic-anchors)
        REGEN="$SCRIPT_DIR/coinbase-attestation-v2-android/make-fixtures.sh country-rkp"
        REGEN_NEEDS="$CIRCUITS_ROOT/../proofport-ai/.env.test"
        ;;
    coinbase-country-attestation-v2-android-factory-synthetic-anchors)
        REGEN="$SCRIPT_DIR/coinbase-attestation-v2-android/make-fixtures.sh country-factory"
        REGEN_NEEDS="$CIRCUITS_ROOT/../proofport-ai/.env.test"
        ;;
    coinbase-attestation-v2-android-synthetic-anchors)
        # coinbase_attestation v2's Android package with Google's root
        # replaced by the synthetic root (make-synthetic-anchors.sh). Real
        # Coinbase attestation, wallet key as above.
        REGEN="$SCRIPT_DIR/coinbase-attestation-v2-android/make-fixtures.sh rkp"
        REGEN_NEEDS="$CIRCUITS_ROOT/../proofport-ai/.env.test"
        ;;
    coinbase-attestation-v2-android-factory-synthetic-anchors)
        # The factory package: Google's RSA root and our Play key replaced by
        # synthetic ones (make-synthetic-anchors.sh). Real Coinbase attestation.
        REGEN="$SCRIPT_DIR/coinbase-attestation-v2-android/make-fixtures.sh factory"
        REGEN_NEEDS="$CIRCUITS_ROOT/../proofport-ai/.env.test"
        ;;
    *)
        echo "No fixture recipe for $CIRCUIT_REL. Add one here rather than running it by hand."
        exit 1
        ;;
esac

cd "$CIRCUIT_DIR"
mkdir -p "$VECTORS"

# Prover.toml is gitignored repo-wide, so a fresh checkout has no fixtures.
# Rebuild them rather than reporting a failure that is really a missing file.
if [ ! -f Prover.toml ] || [ ! -f Prover.no-action.toml ] \
   || { [ "$CIRCUIT_REL" = dojang-playground ] && [ ! -f "$VECTORS/tx_other_signer.toml" ]; } \
   || { [ "$CIRCUIT_REL" = coinbase-attestation-v2-synthetic-anchors ] && [ ! -f "$VECTORS/client_revoked.toml" ]; } \
   || { case "$CIRCUIT_REL" in coinbase-country-attestation-v2*) [ ! -f "$VECTORS/client_other_country.toml" ] ;; *) false ;; esac; } \
   || { [ "$CIRCUIT_REL" = coinbase-attestation-v2-android-synthetic-anchors ] && [ ! -f "$VECTORS/client_revoked.toml" ]; } \
   || { [ "$CIRCUIT_REL" = coinbase-attestation-v2-android-factory-synthetic-anchors ] && [ ! -f "$VECTORS/client_revoked.toml" ]; }; then
  if [ -f "$REGEN_NEEDS" ]; then
    echo "  fixtures missing -- regenerating"
    $REGEN > "$VECTORS/regenerate.log" 2>&1 || {
      echo "  SKIPPED  acceptance run: could not regenerate fixtures"
      sed -n '1,12p' "$VECTORS/regenerate.log" | sed 's/^/           /'
      exit 0
    }
  else
    echo "  SKIPPED  acceptance run: $REGEN_NEEDS is absent, so no fixtures"
    exit 0
  fi
fi

PASSED=0
FAILED=0

