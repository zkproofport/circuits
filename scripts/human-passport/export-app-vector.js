#!/usr/bin/env node
/**
 * Export the accepted human_passport_score fixture (human-passport-score/Prover.toml,
 * action mode) as one JSON vector for the provers' own input builders:
 * proofport-app (src/utils/humanPassport.ts) and proofport-ai hold their
 * builder's flat input vector to `expectedFlat`, the exact vector the circuit
 * accepted in scripts/human-passport/acceptance.sh.
 *
 *   node scripts/human-passport/export-app-vector.js <out.json>
 *
 * The flat order is read from human-passport-score/src/main.nr's parameter
 * list, not restated here. Everything in the vector is public test material:
 * the wallet and issuer keys are derived from public strings in
 * generate-fixtures.js, and the score data is a real Base issuance's.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const CIRCUIT = path.join(ROOT, 'human-passport-score');
const out = process.argv[2];
if (!out) {
  console.error('usage: export-app-vector.js <out.json>');
  process.exit(1);
}

const toml = fs.readFileSync(path.join(CIRCUIT, 'Prover.toml'), 'utf8');
if (!/action mode, must be ACCEPTED/.test(toml)) {
  throw new Error('Prover.toml is not the accepted action-mode fixture; run scripts/human-passport/make-fixtures.sh');
}

/** name -> value: a number/bool string, or a (nested) array of byte strings. */
function parseToml(text) {
  const values = {};
  const body = text.split('\n').filter(l => !l.startsWith('#')).join('\n');
  const re = /^([a-z_]+) = /gm;
  const starts = [];
  let m;
  while ((m = re.exec(body))) starts.push({ name: m[1], at: m.index + m[0].length });
  starts.forEach((s, i) => {
    const raw = body.slice(s.at, i + 1 < starts.length ? starts[i + 1].at - starts[i + 1].name.length - 3 : undefined).trim();
    if (raw.startsWith('[')) {
      values[s.name] = JSON.parse(raw.replace(/0x[0-9a-fA-F]+/g, h => `"${h}"`).replace(/,\s*]/g, ']'));
    } else {
      values[s.name] = raw;
    }
  });
  return values;
}

const v = parseToml(toml);
const mainSrc = fs.readFileSync(path.join(CIRCUIT, 'src/main.nr'), 'utf8');
const sig = mainSrc.match(/fn main\(([\s\S]*?)\)\s*\{/);
if (!sig) throw new Error('fn main not found in human-passport-score/src/main.nr');
const order = [...sig[1].replace(/\/\/[^\n]*/g, '').matchAll(/([a-z_]+)\s*:/g)].map(x => x[1]);

const flat = [];
const asField = x => {
  if (x === 'true') return '1';
  if (x === 'false') return '0';
  return BigInt(x).toString();
};
const push = x => (Array.isArray(x) ? x.forEach(push) : flat.push(asField(x)));
for (const name of order) {
  if (!(name in v)) throw new Error(`Prover.toml has no ${name}`);
  push(v[name]);
}
if (flat.length !== 11164) throw new Error(`flat vector has ${flat.length} entries, expected 11164`);

const hex = bytes => '0x' + bytes.map(b => BigInt(b).toString(16).padStart(2, '0')).join('');
const dataLen = Number(v.score_data_len);
const header = toml.match(/^# Source issuance \(real data bytes\): (0x[0-9a-f]{64})/m);

const vector = {
  note: 'human_passport_score accepted fixture (action mode): INSECURE test wallet and test issuer derived from public strings in circuits scripts/human-passport/generate-fixtures.js; score data is a real Base issuance. Generated by circuits scripts/human-passport/export-app-vector.js.',
  sourceIssuanceTx: header ? header[1] : null,
  scopeString: 'human-passport-score-fixture-scope',
  userAddress: hex(v.user_address),
  userSignatureRS: hex(v.user_signature),
  userPubkey: '0x04' + hex(v.user_pubkey_x).slice(2) + hex(v.user_pubkey_y).slice(2),
  action: { domainSeparator: hex(v.domain_separator), actionHash: hex(v.action_hash) },
  minScoreUnits: Number(v.min_score),
  scorerId: Number(v.scorer_id),
  now: Number(v.now),
  issuance: {
    domainSeparator: hex(v.passport_domain_separator),
    schema: hex(v.schema_uid),
    recipient: hex(v.user_address),
    expirationTime: Number(v.expiration_time),
    revocable: v.revocable === 'true',
    refUID: hex(v.ref_uid),
    value: hex(v.attestation_value),
    nonce: hex(v.request_nonce),
    fee: hex(v.request_fee),
    data: hex(v.score_data.slice(0, dataLen)),
    issuerSignatureRS: hex(v.issuer_signature),
  },
  issuerPubkey: '0x04' + hex(v.issuer_pubkey_x).slice(2) + hex(v.issuer_pubkey_y).slice(2),
  issuerLeafIndex: Number(v.issuer_leaf_index),
  issuerMerkleDepth: Number(v.issuer_merkle_depth),
  issuerMerkleProof: v.issuer_merkle_proof.slice(0, Number(v.issuer_merkle_depth)).map(hex),
  signerListMerkleRoot: hex(v.signer_list_merkle_root),
  expectedNullifier: hex(v.nullifier),
  expectedFlat: flat,
};
fs.writeFileSync(out, JSON.stringify(vector, null, 1) + '\n');
console.log(`wrote ${out}: ${flat.length} inputs in main.nr order (${order.length} parameters)`);
